#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DOC_OUT="$ROOT_DIR/docs/api/discovered.md"

mkdir -p "$(dirname "$DOC_OUT")"

write_section() {
  local title="$1"
  echo -e "\n## $title\n" >> "$DOC_OUT"
}

write_header() {
  cat > "$DOC_OUT" <<'EOF'
# Discovered Public APIs (Generated)

This file is generated by `scripts/discover-public-apis.sh`. Do not edit manually.

EOF
}

scan_lang() {
  local lang_name="$1"; shift
  local glob_expr="$1"; shift
  local grep_expr="$1"; shift

  local matches
  matches=$(find "$ROOT_DIR" -type f \( $(printf "%s" "$glob_expr") \) -not -path "*/.git/*" -print0 \
    | xargs -0 -I{} sh -c "grep -nE --with-filename '$grep_expr' '{}' || true" || true)

  write_section "$lang_name"
  if [[ -z "$matches" ]]; then
    echo "No public items found." >> "$DOC_OUT"
    return
  fi

  echo "$matches" \
    | awk -F: '{file=$1; line=$2; $1=""; $2=""; sub(/^: /, ""); print "- " file ":" line " — " $0}' \
    >> "$DOC_OUT"
}

main() {
  write_header

  # JavaScript / TypeScript
  scan_lang "JavaScript/TypeScript" "-name '*.js' -o -name '*.jsx' -o -name '*.ts' -o -name '*.tsx'" \
    "export\\s+(default|const|function|class|type|interface)|module\\.exports|exports\\."

  # Python
  scan_lang "Python" "-name '*.py'" \
    "^\\s*def\\s+\\w+\\(|^\\s*class\\s+\\w+"

  # Go (exported identifiers start with uppercase)
  scan_lang "Go" "-name '*.go'" \
    "^(func|type)\\s+[A-Z]\\w*"

  # Rust
  scan_lang "Rust" "-name '*.rs'" \
    "^\\s*pub\\s+(fn|struct|enum|trait)\\s+"

  # Java/Kotlin
  scan_lang "Java/Kotlin" "-name '*.java' -o -name '*.kt'" \
    "^\\s*public\\s+"
}

main "$@"